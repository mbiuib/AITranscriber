"""
Загрузчик переводов интерфейса.

Локали хранятся в виде JSON-файлов в папке locales/. Один файл — один язык,
имя файла соответствует коду языка ("ru.json", "en.json"). Файл содержит
плоский словарь "ключ → строка", где ключи сгруппированы по точкам
(например, "upload.title", "toast.saved").

Загруженные локали кэшируются в памяти, чтобы не читать диск при каждом
запросе от UI. Кэш сбрасывается через reload_all() — например, после
ручного редактирования файлов локалей.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict

LOCALES_DIR = Path(__file__).parent.parent / "locales"
_cache: Dict[str, dict] = {}


def available() -> list[str]:
    """
    Возвращает список доступных кодов языков.

    Код языка определяется по имени JSON-файла в LOCALES_DIR без расширения.
    Если папка локалей отсутствует или пуста, возвращается запасной список
    с единственным языком "ru" — приложение в этом случае будет использовать
    fallback-значения из кода.

    Returns:
        Отсортированный по алфавиту список кодов языков (например, ["en", "ru"]).
    """
    if not LOCALES_DIR.exists():
        return ["ru"]
    return sorted(p.stem for p in LOCALES_DIR.glob("*.json"))


def load(lang: str) -> dict:
    """
    Загружает локаль для указанного языка.

    При первом обращении читает файл с диска и кладёт результат в кэш.
    При последующих — возвращает данные из памяти. Если файл для указанного
    языка отсутствует, выполняется fallback на русскую локаль. Если и её
    нет, возвращается пустой словарь — вызывающая сторона должна уметь
    обрабатывать отсутствие переводов (обычно через t(key) = key).

    Args:
        lang: Код языка ("ru", "en", ...).

    Returns:
        Словарь с переводами. Пустой словарь, если файл локали не найден.
    """
    if lang in _cache:
        return _cache[lang]
    f = LOCALES_DIR / f"{lang}.json"
    if not f.exists():
        f = LOCALES_DIR / "ru.json"
    if not f.exists():
        return {}
    data = json.loads(f.read_text(encoding="utf-8"))
    _cache[lang] = data
    return data


def reload_all() -> None:
    """
    Очищает кэш переводов.

    После вызова следующий load() перечитает JSON-файлы с диска. Полезно
    при разработке, когда локали правятся на лету, или если появился
    новый язык и нужно обновить список из available() без перезапуска
    сервера.
    """
    _cache.clear()
